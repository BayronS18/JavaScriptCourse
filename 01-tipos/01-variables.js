/*
 Una variable es un espacio en la memoria que se utiliza para almacenar datos. 
 Se puede declarar utilizando la palabra clave "let" o "var". 
 La diferencia entre ambas es que "let" tiene un alcance de bloque, mientras que "var" tiene un alcance de función. 
 Es recomendable utilizar "let" en lugar de "var" para evitar problemas de alcance y confusión en el código.
*/

let nombre = "Bayron";  // (Declarado y con valor)
let NombreCompleto; // UpperCamelCase (solo declarada sin valor)
let nombreCompleto; // camelCase  (solo declarada sin valor)
let nombre_completo; // snake_case  (solo declarada sin valor)

